#!/usr/bin/env bash
# Builds and installs the Mac app with its browser extension, then removes
# everything the build produced along the way.
#
#   scripts/build-desktop.sh [install-dir]      # default /Applications
#   scripts/build-desktop.sh none               # build only, install nothing
#   KEEP_BUILD=1 scripts/build-desktop.sh       # keep the build files
#
# What this desktop build is:
# - the Rust core, compiled for this Mac only (release), and the Swift
#   binding regenerated from it (scripts/build-apple.sh);
# - Verrou.app in Release, signed ad hoc (no Apple team needed), with the
#   browser extension (Brave and Firefox) and the `verrou` command line
#   tool inside. No iPhone app is built.
#
# Everything below is a build product, none of it is committed, and the
# installed app needs none of it: after a successful install it is all
# removed (unless KEEP_BUILD=1). A rebuild starts cold.
#   target/                     Rust objects and Xcode derived data
#   apple/Frameworks/           the Rust library (xcframework)
#   apple/Shared/Generated/     the Swift binding
#   apple/Helpers/              the CLI and the native messaging host
#   apple/Verrou.xcodeproj/     generated by xcodegen
#   apple/*/Info.plist          generated by xcodegen from project.yml
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

DEST="${1:-/Applications}"
if [[ "$DEST" != none ]]; then
  [[ -d "$DEST" ]] || { echo "install folder not found: $DEST" >&2; exit 2; }
fi

# The whole build and install (Rust, binding, xcodegen, Xcode, signature
# checks) is install-macos.sh; this script only adds the cleanup after it.
VERROU_INSTALL_DIR="$DEST" scripts/install-macos.sh

if [[ "${KEEP_BUILD:-}" == 1 ]]; then
  echo "KEEP_BUILD=1: build files kept"
  exit 0
fi

rm -rf target apple/Frameworks apple/Shared/Generated apple/Helpers apple/Verrou.xcodeproj
rm -f apple/Verrou/Info.plist apple/VerrouAutoFillMac/Info.plist
echo "build files removed"
